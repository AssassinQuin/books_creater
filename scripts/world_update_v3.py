def validate_name(name, context=""):
    ALLOWED_LING_PREFIX = [
        "灵能", "灵晶", "灵衰症", "灵枢", "灵站", "灵册", "灵息",
        "灵装", "灵工", "灵兽", "灵穴", "灵脉", "灵矿", "灵灰岩",
        "灵引", "灵契", "灵植", "灵枢网"
    ]
    issues = []
    if name.startswith("灵"):
        is_allowed = any(name.startswith(p) for p in ALLOWED_LING_PREFIX)
        if not is_allowed:
            issues.append(f"⚠️ 命名警告: '{name}' 滥用'灵'前缀 ({context})")
    return issues


def upsert_setting(cur, novel_id, category, name, keys, secondary_keys, tags, content, 
                   related=None, volume_range="", priority=30, is_constant=False,
                   writing_guide=""):
    """插入或更新世界观数据"""
    related = related or []
    
    data = {
        "keys": keys,
        "secondary_keys": secondary_keys,
        "tags": tags,
        "content": content
    }
    if related:
        data["related"] = related
    if volume_range:
        data["volume_range"] = volume_range
    if writing_guide:
        data["writing_guide"] = writing_guide
    data["priority"] = priority
    data["is_constant"] = is_constant
    
    data_json = json.dumps(data, ensure_ascii=False)
    keys_json = json.dumps(keys, ensure_ascii=False)
    sec_keys_json = json.dumps(secondary_keys, ensure_ascii=False)
    tags_json = json.dumps(tags, ensure_ascii=False)
    
    # Check existing
    cur.execute(
        "SELECT id FROM world_settings WHERE novel_id=? AND category=? AND name=?",
        (novel_id, category, name)
    )
    existing = cur.fetchone()
    
    if existing:
        cur.execute("""
            UPDATE world_settings SET data=?, keys=?, secondary_keys=?, tags=?, 
            priority=?, is_constant=?, updated_at=CURRENT_TIMESTAMP
            WHERE id=?
        """, (data_json, keys_json, sec_keys_json, tags_json, priority, 
              1 if is_constant else 0, existing[0]))
        return existing[0]
    else:
        cur.execute("""
            INSERT INTO world_settings (novel_id, category, name, data, keys, 
            secondary_keys, tags, priority, is_constant, status)
            VALUES (?,?,?,?,?,?,?,?,?,1)
        """, (novel_id, category, name, data_json, keys_json, sec_keys_json, 
              tags_json, priority, 1 if is_constant else 0))
        return cur.lastrowid


