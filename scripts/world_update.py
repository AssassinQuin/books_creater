def upsert_setting(conn, category, name, data, keys=None, secondary_keys=None, tags=None, 
                   related_ids=None, volume_range='', writing_guide='', priority=30, is_constant=0):
    """插入或更新世界设定"""
    if keys is None: keys = []
    if secondary_keys is None: secondary_keys = []
    if tags is None: tags = []
    if related_ids is None: related_ids = []
    
    # Check if exists
    cursor = conn.cursor()
    cursor.execute('SELECT id FROM world_settings WHERE novel_id=1 AND category=? AND name=?', (category, name))
    existing = cursor.fetchone()
    
    data_json = json.dumps(data, ensure_ascii=False) if isinstance(data, dict) else data
    keys_json = json.dumps(keys, ensure_ascii=False)
    sek_json = json.dumps(secondary_keys, ensure_ascii=False)
    tags_json = json.dumps(tags, ensure_ascii=False)
    rel_json = json.dumps(related_ids, ensure_ascii=False)
    
    if existing:
        cursor.execute('''UPDATE world_settings SET data=?, keys=?, secondary_keys=?, tags=?, 
                         related_ids=?, volume_range=?, writing_guide=?, priority=?, is_constant=?,
                         updated_at=CURRENT_TIMESTAMP
                         WHERE novel_id=1 AND category=? AND name=?''',
                      (data_json, keys_json, sek_json, tags_json, rel_json, 
                       volume_range, writing_guide, priority, is_constant, category, name))
    else:
        cursor.execute('''INSERT INTO world_settings (novel_id, category, name, data, keys, secondary_keys, 
                         tags, related_ids, volume_range, writing_guide, priority, is_constant)
                         VALUES (1, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)''',
                      (category, name, data_json, keys_json, sek_json, tags_json, rel_json,
                       volume_range, writing_guide, priority, is_constant))
    return cursor.lastrowid

